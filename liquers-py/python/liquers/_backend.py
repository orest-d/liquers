"""The one place where `liquers` reaches the native extension `_liquers`.

Private. Every public module of `liquers` takes its native names from here, never from `_liquers`
directly, so that a pure-Python implementation can later be put behind this single module
(`PY-HAS-NO-PURE-PYTHON-FALLBACK`) without touching the public modules.

# Main components
- One explicit import of each native class and function, and `__version__`, listed in `__all__`.

# Where it is used
- The public modules (`liquers.query`, `liquers.environment`, ...), `liquers/__init__.py`, and the
  private helpers `_env.py` and `_commands.py`.

# Related concepts
- The fallback contract: a replacement for `_liquers` must provide every name in `__all__`, each
  class reporting the same `__module__` (its public `liquers.<module>`), so that reprs, stubs and the
  API reference stay the same whichever implementation is loaded.
- An `ImportError` from `_liquers` (a missing or broken native library) propagates from here; a
  fallback would catch it here.

# Examples
>>> from liquers import _backend
>>> _backend.Key is __import__("liquers").Key
True
"""

