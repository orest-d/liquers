//! The `RecordBatch` handle: a wasm-safe, zero-copy-on-the-fast-path view into a Liquers record
//! batch's columnar buffers.
//!
//! See `specs/design/record-streams/phase2-architecture.md` §"The wasm route: a dedicated safe
//! mechanism, not Arrow" for the design this implements, and its §"Construction helpers, options
//! and the provider chain" for the exact Rust-side surface pinned here.
//!
//! # The two hazards, and how this handle answers them
//!
//! - **Hazard A — the heap grows.** `memory.grow` detaches the JavaScript `ArrayBuffer` but never
//!   moves the underlying pages, so a stale view is a `view.buffer !== memory.buffer` check away
//!   from detection, and the fix is re-creating the view at the *same* pointer and length. This
//!   handle does nothing special for it — the descriptor never caches a view, only the pointer and
//!   length a caller (or the `RecordColumn` companion, `records_column.js`) turns into one.
//! - **Hazard B — the buffer is freed or moved.** Prevented, not detected: [`LiquersRecordBatch`]
//!   holds an `Arc<RecordBatch>`, and every buffer inside it is `Arc`-shared and immutable once
//!   built, so as long as JavaScript holds this handle the pointers a descriptor hands out stay
//!   valid. `free()` (generated by `wasm-bindgen`) drops the `Arc`; a typed-array view held past
//!   that point is Hazard B with no detection — the caller's discipline, documented rather than
//!   enforced.
//!
//! A `RecordView` that is not already a `RecordBatch` is materialized before it reaches this
//! handle (`default_value.rs`'s `to_js_custom`) — free for a batch, and the only way to give
//! JavaScript stable pointers into a view's *computed* columns.
//!
//! # Descriptors read the batch's own storage, not a copy
//!
//! [`LiquersRecordBatch::column`] reads `self.inner.columns[i]` directly rather than going through
//! [`liquers_lib::records::RecordView::column`], whose default/`RecordBatch` implementation calls
//! `Column::slice`, which **copies** (documented on `Column::slice` as
//! `COLUMN-SLICE-COPIES-INSTEAD-OF-SHARING-BUFFER-STORAGE`). A descriptor built from that copy would point
//! into a `Column` value that is dropped the moment this function returns — a pointer to freed
//! memory before the caller ever reads it. Reading `inner.columns[i]` by reference keeps the
//! pointer inside the buffer the handle's own `Arc<RecordBatch>` keeps alive.

