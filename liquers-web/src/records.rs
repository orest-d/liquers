/// What a live handle stands for: the value Rust gets back when the handle crosses back.
#[derive(Clone)]
pub(crate) enum RecordHandle {
    View(Arc<dyn RecordView>),
    Source(Arc<dyn RecordSource>),
}

thread_local! {
    /// Live record handles by id. A wasm-bindgen handle cannot be borrowed back from a `JsValue`
    /// without consuming it, which would invalidate the page's handle on a read-only pass-through,
    /// so each handle carries an id (`__liquersRecordHandle`) and this maps the id to the `Arc` the
    /// handle was made from. Filled when a handle is constructed and emptied when it is dropped
    /// (`free()`), so it holds an `Arc` exactly as long as JavaScript holds the handle.
    ///
    /// Single-threaded wasm: `RefCell` is enough, and no borrow is held across an `await` or a call
    /// into JavaScript.
    static HANDLES: RefCell<HashMap<u32, RecordHandle>> = RefCell::new(HashMap::new());
    static NEXT_HANDLE_ID: Cell<u32> = const { Cell::new(1) };
}

fn register_handle(handle: RecordHandle) -> u32 {
    let id = NEXT_HANDLE_ID.with(|next| {
        let id = next.get();
        // Wrapping past `u32::MAX` would take four billion handles; skipping 0 keeps it usable as
        // "no handle" in a debugger.
        next.set(id.checked_add(1).unwrap_or(1));
        id
    });
    HANDLES.with(|handles| handles.borrow_mut().insert(id, handle));
    id
}

fn release_handle(id: u32) {
    // Removed before dropping: the `Arc`'s own drop runs after the borrow ends.
    let removed = HANDLES.with(|handles| handles.borrow_mut().remove(&id));
    drop(removed);
}

/// The value a live handle stands for, or `None` once it has been freed.
pub(crate) fn lookup_handle(id: u32) -> Option<RecordHandle> {
    HANDLES.with(|handles| handles.borrow().get(&id).cloned())
}

/// Whether the registry holds `id`. Test support for `RECORDS06`.
pub fn handle_is_live(id: u32) -> bool {
    lookup_handle(id).is_some()
}

#[cfg(feature = "debug-handles")]
static LIVE_BATCH_HANDLES: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

/// Live [`LiquersRecordBatch`] handles — `RUNTIME05`'s idiom (`command::adapter::live_handle_count`),
/// applied to batches. Test-only, behind `debug-handles`: `RECORDS06` asserts it returns to
/// baseline after `free()`, which is the only way a JavaScript caller can observe that the `Arc`
/// was actually dropped rather than merely unreferenced.
#[cfg(feature = "debug-handles")]
pub fn live_batch_handle_count() -> usize {
    LIVE_BATCH_HANDLES.load(std::sync::atomic::Ordering::SeqCst)
}

/// A Liquers record batch, visible to JavaScript.
///
/// Holds the batch by `Arc`, which is the whole of Hazard B's answer — see the module
/// documentation. Cloning a `LiquersRecordBatch` (there is no such method; construct a new one
/// from the same `Arc<RecordBatch>` instead) would share the same guarantee.
#[wasm_bindgen(js_name = RecordBatch)]
pub struct LiquersRecordBatch {
    inner: Arc<RecordBatch>,
    id: u32,
}

#[wasm_bindgen(js_class = RecordBatch)]
impl LiquersRecordBatch {
    #[wasm_bindgen(getter, js_name = numRows)]
    pub fn num_rows(&self) -> usize {
        self.inner.len
    }

    #[wasm_bindgen(getter, js_name = numColumns)]
    pub fn num_columns(&self) -> usize {
        self.inner.columns.len()
    }

    /// The batch's schema, as JSON (`RecordSchema`'s own `Serialize`).
    ///
    /// Returns `"{}"` on the serialization failure that never happens in practice — every field
    /// `RecordSchema` carries is `Serialize` — rather than a `String`-returning method having no
    /// `Result` to propagate one through; see the "no `unwrap`/`expect`" rule this avoids.
    #[wasm_bindgen(js_name = schemaJson)]
    pub fn schema_json(&self) -> String {
        serde_json::to_string(self.inner.schema.as_ref()).unwrap_or_else(|_| "{}".to_string())
    }

    /// Descriptor for column `i`: `{ kind, ptr, len, validity }`, plus `dim` for `"Vector"` and
    /// `offsets`/`data` for `"Text"`/`"Binary"` in place of `ptr`/`len`. See
    /// [`LiquersRecordColumnDescriptor`](crate::typescript::JsRecordColumnDescriptor)'s
    /// TypeScript declaration for the full shape. Carries no data itself — building a typed-array
    /// view from it is the caller's job (or `RecordColumn`'s, `records_column.js`).
    pub fn column(&self, i: usize) -> Result<JsRecordColumnDescriptor, JsValue> {
        column_descriptor(&self.inner, i)
            .map(|obj| obj.unchecked_into())
            .map_err(liquers_error_to_js)
    }

    /// The always-safe fallback: an owned copy, detached from linear memory. O(n). See
    /// [`LiquersRecordColumnCopy`](crate::typescript::JsRecordColumnCopy)'s TypeScript declaration
    /// (injected into `liquers_web.d.ts` for documentation) for exactly what each column kind
    /// copies to.
    ///
    /// Returns a plain `JsValue` rather than the `JsRecordColumnCopy` alias `column()` uses:
    /// unlike a descriptor, a copy is meant to be `dyn_into::<SpecificType>()`'d immediately, and
    /// `dyn_into`'s `Err` side is `Self` — a wrapper type with no `Debug` impl would make that
    /// call's `.expect(...)` fail to compile for every caller, Rust or JavaScript-facing alike.
    #[wasm_bindgen(js_name = columnCopy)]
    pub fn column_copy(&self, i: usize) -> Result<JsValue, JsValue> {
        column_copy(&self.inner, i).map_err(liquers_error_to_js)
    }

    /// A ready-made `RecordColumn` companion (`records_column.js`) for column `i`, built from
    /// this module's own linear memory ([`wasm_bindgen::memory`]) and [`Self::column`]'s
    /// descriptor. Purely a convenience over constructing one by hand.
    #[wasm_bindgen(js_name = columnView)]
    pub fn column_view(&self, i: usize) -> Result<JsValue, JsValue> {
        let descriptor = self.column(i)?;
        let memory = wasm_bindgen::memory();
        Ok(JsRecordColumn::new(&memory, descriptor.as_ref()).into())
    }

    /// The batch's `chunk_id`, as JSON (`null` when it has none) — where its rows were produced.
    #[wasm_bindgen(js_name = chunkIdJson)]
    pub fn chunk_id_json(&self) -> String {
        serde_json::to_string(&self.inner.chunk_id).unwrap_or_else(|_| "null".to_string())
    }

    /// The batch's `sources` dictionary (`ChunkOrigin` entries), as JSON.
    #[wasm_bindgen(js_name = sourcesJson)]
    pub fn sources_json(&self) -> String {
        serde_json::to_string(&self.inner.sources).unwrap_or_else(|_| "[]".to_string())
    }

    /// The registry id that lets this handle cross back into Liquers as the value it was made from.
    /// Not for pages to use; its presence is how the bridge recognizes a record handle.
    #[wasm_bindgen(getter, js_name = __liquersRecordHandle)]
    pub fn handle_id(&self) -> u32 {
        self.id
    }
}

impl LiquersRecordBatch {
    /// A handle for `batch` that crosses back as `view`, the value it was materialized from — so a
    /// page that hands the batch back gives Rust the same `Arc`, not the materialized copy.
    pub fn from_view(view: Arc<dyn RecordView>, batch: Arc<RecordBatch>) -> Self {
        #[cfg(feature = "debug-handles")]
        LIVE_BATCH_HANDLES.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        let id = register_handle(RecordHandle::View(view));
        LiquersRecordBatch { inner: batch, id }
    }
}

impl From<Arc<RecordBatch>> for LiquersRecordBatch {
    fn from(inner: Arc<RecordBatch>) -> Self {
        let view: Arc<dyn RecordView> = inner.clone();
        LiquersRecordBatch::from_view(view, inner)
    }
}

/// Unconditional: the registry entry goes with the handle. Only the live count is test-only.
impl Drop for LiquersRecordBatch {
    fn drop(&mut self) {
        release_handle(self.id);
        #[cfg(feature = "debug-handles")]
        LIVE_BATCH_HANDLES.fetch_sub(1, std::sync::atomic::Ordering::SeqCst);
    }
}

/// A Liquers record source, visible to JavaScript: a possibly large, chunked table whose chunks
/// are evaluated only when read.
///
/// Traversal (`stream`, `materialize`) evaluates chunks in the web environment, resolved afresh at
/// each call, so a rebuild between calls is harmless. `chunks()` evaluates
/// nothing.
#[wasm_bindgen(js_name = RecordSource)]
pub struct LiquersRecordSource {
    inner: Arc<dyn RecordSource>,
    id: u32,
    /// The environment whose evaluation produced the source; chunks resolve through it.
    origin: Origin,
}

/// Which environment a source handle resolves its chunks through.
#[derive(Clone)]
enum Origin {
    /// The singleton, re-resolved on every use so that a rebuild (a command registered later) is
    /// visible.
    Global,
    /// An explicit `new Environment()` instance, which is never rebuilt and so is held.
    Explicit(liquers_core::context::EnvRef<crate::environment::WebEnvironment>),
}

impl Origin {
    /// The origin of the conversion in progress: the environment it runs in, or the singleton
    /// when the caller named none or named the singleton, current or before a rebuild.
    fn of_current_conversion() -> Origin {
        match crate::bridge::conversion_env::<crate::environment::WebEnvironment>() {
            Some(env) if crate::environment::is_singleton(&env) => Origin::Global,
            Some(env) => Origin::Explicit(env),
            None => Origin::Global,
        }
    }

    fn resolver(&self) -> Result<Arc<dyn liquers_lib::records::ChunkResolver>, JsValue> {
        let envref = match self {
            Origin::Global => crate::environment::shared_env().map_err(liquers_error_to_js)?,
            Origin::Explicit(envref) => envref.clone(),
        };
        Ok(Arc::new(EnvResolver::new(envref)))
    }
}

#[wasm_bindgen(js_class = RecordSource)]
impl LiquersRecordSource {
    /// Every known chunk as `{ kind, query }`, without evaluating any: `kind` is `"query"` for an
    /// unkeyed chunk and `"key"` for a stored one, and `query` evaluates to the chunk either way.
    /// A view held in memory has no query that produces it: its `kind` is `"memory"` and its
    /// `query` is only a label. For an unbounded source, only the chunks computed so far.
    #[wasm_bindgen(unchecked_return_type = "LiquersRecordChunk[]")]
    pub fn chunks(&self) -> Result<JsValue, JsValue> {
        let ids = match self.inner.chunks() {
            ChunkList::Known(ids) => ids,
            ChunkList::Unbounded { computed } => computed,
        };
        let list = js_sys::Array::new();
        for id in ids {
            let (kind, query) = match id {
                ChunkId::Query(query) if InMemorySource::is_placeholder_chunk_id(id) => {
                    ("memory", query.encode())
                }
                ChunkId::Query(query) => ("query", query.encode()),
                ChunkId::Key(key) => ("key", liquers_core::query::Query::from(key.clone()).encode()),
            };
            let entry = js_sys::Object::new();
            set(&entry, "kind", &JsValue::from_str(kind)).map_err(liquers_error_to_js)?;
            set(&entry, "query", &JsValue::from_str(&query)).map_err(liquers_error_to_js)?;
            list.push(&entry);
        }
        Ok(list.into())
    }

    /// Whether every chunk is known in advance. An unbounded source ends at its first short chunk.
    #[wasm_bindgen(getter)]
    pub fn bounded(&self) -> bool {
        match self.inner.chunks() {
            ChunkList::Known(_) => true,
            ChunkList::Unbounded { .. } => false,
        }
    }

    /// The schema every batch will have, as JSON, when the source declares one.
    #[wasm_bindgen(js_name = schemaJson)]
    pub fn schema_json(&self) -> Option<String> {
        self.inner
            .schema()
            .and_then(|schema| serde_json::to_string(schema.as_ref()).ok())
    }

    /// The manifest the source was built from, as JSON, when it has one.
    #[wasm_bindgen(js_name = manifestJson)]
    pub fn manifest_json(&self) -> Option<String> {
        self.inner
            .manifest()
            .and_then(|manifest| serde_json::to_string(manifest).ok())
    }

    /// Resolves to an async iterable yielding one `RecordBatch` per view, in order. Each call opens
    /// a fresh traversal. Abandoning the loop (`break`) frees the stream; an evaluation already
    /// running for the current chunk still finishes (cancellation is inert in this build).
    #[wasm_bindgen(unchecked_return_type = "Promise<AsyncIterableIterator<RecordBatch>>")]
    pub fn stream(&self) -> js_sys::Promise {
        let source = self.inner.clone();
        let origin = self.origin.clone();
        wasm_bindgen_futures::future_to_promise(async move {
            let stream = source
                .stream(origin.resolver()?)
                .await
                .map_err(liquers_error_to_js)?;
            let handle = LiquersRecordStream {
                state: Rc::new(RefCell::new(StreamState::Ready(stream))),
            };
            Ok(async_iterable(&JsValue::from(handle)))
        })
    }

    /// Resolves to every row as one `RecordBatch`, or rejects when the source has more than
    /// `maxRows` rows or its chunks' schemas differ.
    #[wasm_bindgen(unchecked_return_type = "Promise<RecordBatch>")]
    pub fn materialize(
        &self,
        #[wasm_bindgen(js_name = maxRows)] max_rows: usize,
    ) -> js_sys::Promise {
        let source = self.inner.clone();
        let origin = self.origin.clone();
        wasm_bindgen_futures::future_to_promise(async move {
            let batch = source
                .materialize(origin.resolver()?, max_rows)
                .await
                .map_err(liquers_error_to_js)?;
            Ok(LiquersRecordBatch::from(batch).into())
        })
    }

    /// The registry id that lets this handle cross back into Liquers as the same source.
    #[wasm_bindgen(getter, js_name = __liquersRecordHandle)]
    pub fn handle_id(&self) -> u32 {
        self.id
    }
}

impl From<Arc<dyn RecordSource>> for LiquersRecordSource {
    fn from(inner: Arc<dyn RecordSource>) -> Self {
        let id = register_handle(RecordHandle::Source(inner.clone()));
        LiquersRecordSource {
            inner,
            id,
            origin: Origin::of_current_conversion(),
        }
    }
}

impl Drop for LiquersRecordSource {
    fn drop(&mut self) {
        release_handle(self.id);
    }
}

enum StreamState {
    Ready(BoxRecordStream),
    /// A `nextBatch` is awaiting the stream, which it has taken out of the cell.
    Pending,
    Done,
}

/// One traversal of a [`LiquersRecordSource`]. Pages use it through the async iterable `stream()`
/// returns; `nextBatch` is the primitive under it.
#[wasm_bindgen(js_name = RecordStream)]
pub struct LiquersRecordStream {
    state: Rc<RefCell<StreamState>>,
}

#[wasm_bindgen(js_class = RecordStream)]
impl LiquersRecordStream {
    /// Resolves to the next `RecordBatch`, or `null` at the end. A call made while the previous
    /// one is still pending is rejected: the stream is held by that call.
    #[wasm_bindgen(js_name = nextBatch, unchecked_return_type = "Promise<RecordBatch | null>")]
    pub fn next_batch(&self) -> js_sys::Promise {
        let state = self.state.clone();
        wasm_bindgen_futures::future_to_promise(async move {
            next_view(&state)
                .await
                .map(|view| match view {
                    Some(handle) => handle.into(),
                    None => JsValue::NULL,
                })
                .map_err(liquers_error_to_js)
        })
    }
}

/// Takes the stream out of its cell for the `await` — a `RefCell` borrow held across it would be
/// the `already borrowed` panic this crate's borrow rule forbids — and puts it back after.
async fn next_view(state: &RefCell<StreamState>) -> Result<Option<LiquersRecordBatch>, Error> {
    use futures::StreamExt;
    let taken = std::mem::replace(&mut *state.borrow_mut(), StreamState::Pending);
    let mut stream = match taken {
        StreamState::Ready(stream) => stream,
        StreamState::Pending => {
            return Err(Error::general_error(
                "RecordStream.nextBatch called while a previous call is pending".to_string(),
            ))
        }
        StreamState::Done => {
            *state.borrow_mut() = StreamState::Done;
            return Ok(None);
        }
    };
    let next = stream.next().await;
    match next {
        Some(Ok(view)) => {
            *state.borrow_mut() = StreamState::Ready(stream);
            let batch = view.materialize()?;
            Ok(Some(LiquersRecordBatch::from_view(view, batch)))
        }
        Some(Err(e)) => {
            *state.borrow_mut() = StreamState::Done;
            Err(e)
        }
        None => {
            *state.borrow_mut() = StreamState::Done;
            Ok(None)
        }
    }
}

/// Row `i` is valid (non-null) — `None` means no validity buffer at all, every row valid. A
/// free-standing copy of `Column`'s own private helper: that one is not part of this crate's
/// public surface, and duplicating a five-line predicate is cheaper than widening it.
fn is_row_valid(validity: &Option<Bitmap>, i: usize) -> bool {
    match validity {
        Some(bitmap) => bitmap.get(i),
        None => true,
    }
}

/// Sets one property on a plain object, reporting the (practically unreachable — the key is
/// always a valid property name and the object is never frozen) failure as a typed [`Error`]
/// rather than swallowing it, following `command/adapter.rs`'s `call_js_command` convention.
fn set(obj: &js_sys::Object, key: &str, value: &JsValue) -> Result<(), Error> {
    js_sys::Reflect::set(obj, &JsValue::from_str(key), value)
        .map(|_| ())
        .map_err(|_| {
            Error::from_error(
                ErrorType::ConversionError,
                format!("Could not set {key:?} on a record column descriptor"),
            )
        })
}

/// A plain `{ kind, ptr, len }` descriptor — the shape every leaf of
/// [`JsRecordColumnDescriptor`](crate::typescript::JsRecordColumnDescriptor) shares.
fn leaf_descriptor(kind: &str, ptr: usize, len: usize) -> Result<js_sys::Object, Error> {
    let obj = js_sys::Object::new();
    set(&obj, "kind", &JsValue::from_str(kind))?;
    set(&obj, "ptr", &JsValue::from_f64(ptr as f64))?;
    set(&obj, "len", &JsValue::from_f64(len as f64))?;
    Ok(obj)
}

/// The `validity` field: `null`, or a `"Bitmap"`-kind leaf descriptor over the packed bytes.
///
/// `len` on that leaf is the **byte** length of the packed storage (`bitmap.as_bytes().len()`),
/// consistent with every other leaf's `len` meaning "elements of `kind` at `ptr`" — a `"Bitmap"`
/// element is a byte. `rows` carries the logical bit count separately, since `len.saturating_mul(8)`
/// may overcount by up to 7 padding bits in the last byte.
fn validity_descriptor(validity: &Option<Bitmap>) -> Result<JsValue, Error> {
    match validity {
        None => Ok(JsValue::NULL),
        Some(bitmap) => {
            let bytes = bitmap.as_bytes();
            let obj = leaf_descriptor("Bitmap", bytes.as_ptr() as usize, bytes.len())?;
            set(&obj, "rows", &JsValue::from_f64(bitmap.len() as f64))?;
            Ok(obj.into())
        }
    }
}

/// A column descriptor built from one leaf plus `validity`, and any further fields a kind needs
/// (`dim` for `"Vector"`'s row width, `rows` for `"BoolBitmap"`'s logical bit count).
fn numeric_descriptor(
    kind: &str,
    ptr: usize,
    len: usize,
    extra: &[(&str, f64)],
    validity: &Option<Bitmap>,
) -> Result<js_sys::Object, Error> {
    let obj = leaf_descriptor(kind, ptr, len)?;
    for (key, value) in extra {
        set(&obj, key, &JsValue::from_f64(*value))?;
    }
    set(&obj, "validity", &validity_descriptor(validity)?)?;
    Ok(obj)
}

/// `Text`/`Binary`'s descriptor: no top-level `ptr`/`len` (there are two buffers), an `offsets`
/// leaf (`"Int32"`, `numRows + 1` entries) and a `data` leaf (`"Uint8"`, the concatenated bytes).
fn byte_column_descriptor(
    kind: &str,
    validity: &Option<Bitmap>,
    offsets: &Buffer<i32>,
    data: &AlignedBuffer,
) -> Result<js_sys::Object, Error> {
    let obj = js_sys::Object::new();
    set(&obj, "kind", &JsValue::from_str(kind))?;
    let off = offsets.as_slice();
    let offsets_desc = leaf_descriptor("Int32", off.as_ptr() as usize, off.len())?;
    set(&obj, "offsets", &offsets_desc.into())?;
    let bytes = data.as_bytes();
    let data_desc = leaf_descriptor("Uint8", bytes.as_ptr() as usize, bytes.len())?;
    set(&obj, "data", &data_desc.into())?;
    set(&obj, "validity", &validity_descriptor(validity)?)?;
    Ok(obj)
}

/// The column at `i`, borrowed straight out of the batch's own storage — see the module
/// documentation for why this bypasses `RecordView::column`.
fn column_of(batch: &RecordBatch, i: usize) -> Result<&Column, Error> {
    batch.columns.get(i).ok_or_else(|| {
        Error::general_error(format!(
            "RecordBatch::column: column index {i} out of range (0..{})",
            batch.columns.len()
        ))
    })
}

/// Builds the descriptor object for [`LiquersRecordBatch::column`]. Exhaustive over every
/// [`Column`] variant — CLAUDE.md's "Match Statements" convention forbids a default arm on a
/// Liquers-owned enum, so a future `Column` kind is a compile error here, not a silently missing
/// descriptor.
fn column_descriptor(batch: &RecordBatch, i: usize) -> Result<js_sys::Object, Error> {
    match column_of(batch, i)? {
        Column::Int { validity, values } => {
            let slice = values.as_slice();
            numeric_descriptor("Int", slice.as_ptr() as usize, slice.len(), &[], validity)
        }
        Column::UInt { validity, values } => {
            let slice = values.as_slice();
            numeric_descriptor("UInt", slice.as_ptr() as usize, slice.len(), &[], validity)
        }
        Column::Float { validity, values } => {
            let slice = values.as_slice();
            numeric_descriptor("Float", slice.as_ptr() as usize, slice.len(), &[], validity)
        }
        Column::Date { validity, values } => {
            let slice = values.as_slice();
            numeric_descriptor("Date", slice.as_ptr() as usize, slice.len(), &[], validity)
        }
        Column::Timestamp { validity, values } => {
            let slice = values.as_slice();
            numeric_descriptor("Timestamp", slice.as_ptr() as usize, slice.len(), &[], validity)
        }
        Column::Vector { validity, dim, data } => {
            let slice = data.as_slice();
            let extra = [("dim", *dim as f64)];
            numeric_descriptor("Vector", slice.as_ptr() as usize, slice.len(), &extra, validity)
        }
        Column::Bool { validity, values } => {
            // Bit-packed: `len` is the *byte* length of the packed storage (matching every other
            // leaf's "elements of `kind` at `ptr`"), and `rows` carries the logical bit count
            // separately — the "BoolBitmap" kind exists so a caller cannot mistake this pointer
            // for one byte per row.
            let bytes = values.as_bytes();
            let extra = [("rows", values.len() as f64)];
            numeric_descriptor("BoolBitmap", bytes.as_ptr() as usize, bytes.len(), &extra, validity)
        }
        Column::Text { validity, offsets, data } => byte_column_descriptor("Text", validity, offsets, data),
        Column::Binary { validity, offsets, data } => {
            byte_column_descriptor("Binary", validity, offsets, data)
        }
    }
}

/// Builds the owned copy for [`LiquersRecordBatch::column_copy`]. Exhaustive over every [`Column`]
/// variant for the same reason as [`column_descriptor`].
fn column_copy(batch: &RecordBatch, i: usize) -> Result<JsValue, Error> {
    match column_of(batch, i)? {
        Column::Int { values, .. } => Ok(js_sys::BigInt64Array::from(values.as_slice()).into()),
        Column::UInt { values, .. } => Ok(js_sys::BigUint64Array::from(values.as_slice()).into()),
        Column::Float { values, .. } => Ok(js_sys::Float64Array::from(values.as_slice()).into()),
        Column::Date { values, .. } => Ok(js_sys::Int32Array::from(values.as_slice()).into()),
        Column::Timestamp { values, .. } => Ok(js_sys::BigInt64Array::from(values.as_slice()).into()),
        // Unpacked to one byte (0/1) per row — a fast, null-blind raw copy, like the other
        // numeric kinds above. `column`'s `validity` descriptor is the way to learn which rows
        // are actually null; `columnCopy` never distinguishes them for any numeric kind.
        Column::Bool { values, .. } => {
            let unpacked: Vec<u8> = (0..values.len()).map(|row| values.get(row) as u8).collect();
            Ok(js_sys::Uint8Array::from(unpacked.as_slice()).into())
        }
        Column::Text { validity, offsets, data } => text_copy(validity, offsets, data),
        Column::Binary { validity, offsets, data } => binary_copy(validity, offsets, data),
        Column::Vector { validity, dim, data } => vector_copy(validity, *dim, data),
    }
}

/// `Text`'s copy: an array of JavaScript strings, `null` for a null cell — chosen over a typed
/// array because there is no typed array of variable-length UTF-8 strings.
fn text_copy(validity: &Option<Bitmap>, offsets: &Buffer<i32>, data: &AlignedBuffer) -> Result<JsValue, Error> {
    let off = offsets.as_slice();
    let bytes = data.as_bytes();
    let rows = off.len().saturating_sub(1);
    let array = js_sys::Array::new();
    for row in 0..rows {
        if !is_row_valid(validity, row) {
            array.push(&JsValue::NULL);
            continue;
        }
        let start = off[row] as usize;
        let end = off[row + 1] as usize;
        let text = std::str::from_utf8(&bytes[start..end])
            .map_err(|e| Error::from_error(ErrorType::ConversionError, e))?;
        array.push(&JsValue::from_str(text));
    }
    Ok(array.into())
}

/// `Binary`'s copy: an array of per-row `Uint8Array`s, `null` for a null cell — chosen over a
/// single flat `Uint8Array` because each row's byte length differs and a caller needs the
/// boundary, which `columnCopy` (unlike `column`) does not separately expose.
fn binary_copy(
    validity: &Option<Bitmap>,
    offsets: &Buffer<i32>,
    data: &AlignedBuffer,
) -> Result<JsValue, Error> {
    let off = offsets.as_slice();
    let bytes = data.as_bytes();
    let rows = off.len().saturating_sub(1);
    let array = js_sys::Array::new();
    for row in 0..rows {
        if !is_row_valid(validity, row) {
            array.push(&JsValue::NULL);
            continue;
        }
        let start = off[row] as usize;
        let end = off[row + 1] as usize;
        array.push(&js_sys::Uint8Array::from(&bytes[start..end]).into());
    }
    Ok(array.into())
}

/// `Vector`'s copy: an array of per-row `Float32Array`s (each `dim` elements), `null` for a null
/// cell — chosen over one flat `Float32Array` so a row's boundary survives the copy without a
/// caller having to know `dim` separately.
fn vector_copy(validity: &Option<Bitmap>, dim: usize, data: &Buffer<f32>) -> Result<JsValue, Error> {
    let slice = data.as_slice();
    // An all-null Vector column has no width (`dim == 0`) and no data; its row count is the
    // validity bitmap's, as `Column::len` has it.
    let rows = if dim == 0 {
        validity.as_ref().map_or(0, Bitmap::len)
    } else {
        slice.len() / dim
    };
    let array = js_sys::Array::new();
    for row in 0..rows {
        if !is_row_valid(validity, row) {
            array.push(&JsValue::NULL);
            continue;
        }
        let start = row * dim;
        let end = start + dim;
        array.push(&js_sys::Float32Array::from(&slice[start..end]).into());
    }
    Ok(array.into())
}

#[cfg(all(test, target_arch = "wasm32"))]
mod tests {
    use super::*;
    use liquers_lib::records::record_stream;
    use wasm_bindgen_test::*;

    /// A second `nextBatch` while the first is pending is refused, and the first still completes.
    #[wasm_bindgen_test]
    async fn next_batch_refuses_a_concurrent_call() {
        let (sender, receiver) = futures::channel::mpsc::unbounded::<Result<Arc<dyn RecordView>, Error>>();
        let state = Rc::new(RefCell::new(StreamState::Ready(record_stream(receiver, None))));

        let first = next_view(&state);
        futures::pin_mut!(first);
        // Poll once so the first call takes the stream and waits on the empty channel.
        assert!(futures::poll!(first.as_mut()).is_pending());

        let second = next_view(&state).await;
        match second {
            Err(e) => assert!(e.message.contains("pending"), "{}", e.message),
            Ok(_) => panic!("a concurrent nextBatch must be refused"),
        }

        drop(sender);
        assert!(first.await.expect("the first call completes").is_none());
    }
}
