//! `OBJECT*` and `ERROR*` conformance tests.
//!
//! Pure value/parse semantics — no DOM — so these run under Node. See
//! `specs/liquers-web/phase3-examples.md` for the inventory.

#![cfg(target_arch = "wasm32")]

use liquers_core::error::ErrorType;
use liquers_web::error::{error_type_from_name, error_type_name, LiquersError};
use liquers_web::{LiquersKey, LiquersQuery};
use wasm_bindgen::prelude::*;
use wasm_bindgen_test::*;

/// Every `ErrorType` variant. Listed explicitly rather than iterated, because the enum has no
/// iterator — if a variant is added, `error_type_name`'s exhaustive match fails to compile, and
/// this list is then updated to match.
const ALL_ERROR_TYPES: &[ErrorType] = &[
    ErrorType::ArgumentMissing,
    ErrorType::ActionNotRegistered,
    ErrorType::CommandAlreadyRegistered,
    ErrorType::ParseError,
    ErrorType::ParameterError,
    ErrorType::TooManyParameters,
    ErrorType::ConversionError,
    ErrorType::SerializationError,
    ErrorType::General,
    ErrorType::CacheNotSupported,
    ErrorType::UnknownCommand,
    ErrorType::NotSupported,
    ErrorType::NotAvailable,
    ErrorType::KeyNotFound,
    ErrorType::KeyNotSupported,
    ErrorType::KeyReadError,
    ErrorType::KeyWriteError,
    ErrorType::UnexpectedError,
    ErrorType::ExecutionError,
    ErrorType::DependencyVersionMismatch,
    ErrorType::DependencyCycle,
    ErrorType::Cancelled,
];

/// OBJECT01 — query parse/encode round-trips.
#[wasm_bindgen_test]
fn object01_query_parse_encode_roundtrip() {
    for text in ["hello", "hello/greet", "hello/repeat-3", "hello/ns-myapp/shout"] {
        let q = LiquersQuery::parse(text).expect("parse");
        assert_eq!(q.encode(), text, "round trip changed the query");
        assert_eq!(q.to_string_js(), text, "toString must agree with encode");
    }
}

/// OBJECT02 — key equality and the hash contract.
#[wasm_bindgen_test]
fn object02_key_equality_and_hash() {
    let a = LiquersKey::parse("d/f").expect("parse a");
    let b = LiquersKey::parse("d/f").expect("parse b");
    let c = LiquersKey::parse("d/g").expect("parse c");

    assert!(a.equals(&b), "equal keys must compare equal");
    assert!(!a.equals(&c));
    // The hash contract: equal keys encode identically, so the encoding is a usable map key.
    assert_eq!(a.encode(), b.encode());
    assert_ne!(a.encode(), c.encode());

    assert_eq!(a.parent().encode(), "d");
    assert_eq!(a.filename().as_deref(), Some("f"));
}

